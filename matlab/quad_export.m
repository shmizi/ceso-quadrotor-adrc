function quad_export(log, filename)
names = {'time_s', 'x_m', 'y_m', 'z_m', 'xref_m', 'yref_m', 'zref_m', ...
    'roll_rad', 'pitch_rad', 'yaw_rad', 'rollref_rad', 'pitchref_rad', 'yawref_rad', ...
    'motor1_N', 'motor2_N', 'motor3_N', 'motor4_N', 'fstar_x', 'fstar_y', 'fstar_z', ...
    'fstar_roll', 'fstar_pitch', 'fstar_yaw', 'saturated'};

data = [log.time, log.state(:,1:3), log.reference, log.euler, log.attitude_reference, ...
    log.state(:,14:17), log.estimate, double(log.saturated)];

writetable(array2table(data, 'VariableNames', names), filename);
end
